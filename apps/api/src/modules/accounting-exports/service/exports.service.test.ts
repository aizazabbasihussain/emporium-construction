import ExcelJS from 'exceljs';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import {
  ACCOUNTANT,
  MANAGEMENT,
  NOBODY,
  SUPERVISOR,
  createAccountingKit,
  receiptRow,
  type AccountingKit,
} from '../test-support.js';
import type { Db, ExportCode } from '../types.js';

let kit: AccountingKit;
beforeAll(async () => {
  kit = await createAccountingKit();
}, 120_000);
afterAll(() => kit.close());
beforeEach(async () => {
  kit.attached.length = 0;
  kit.now.current = new Date('2026-10-25T10:00:00Z');
  await kit.db.query('delete from acc_tags');
});

const accountant = () => kit.actorFor(ACCOUNTANT);
const inTx = <T>(run: (tx: Db) => Promise<T>) => kit.db.transaction(run);
const period = { from: '2026-10-01', to: '2026-10-31' };
const run = (code: ExportCode = 'receipts_register', filters = period, actor = accountant()) =>
  inTx((tx) => kit.exports.run(code, filters, actor, tx));

/** Two receipts worked out by hand: 100,000.00 + 250,500.50 = 350,500.50. */
const scriptReceipts = () => {
  kit.loaded.receipts_register = {
    rows: [receiptRow('RV-1', '100000.00'), receiptRow('RV-2', '250500.50')],
    control: { amount: '350500.50', withheld: '0.00' },
  };
};

const setFiscalStart = async (month: number, expectedVersion: number) =>
  inTx((tx) =>
    kit.platform.settings.set(
      { key: 'accounting.fiscal_year_start_month', value: month, expectedVersion },
      { actorUserId: null, requestId: null },
      tx,
    ),
  );

describe('the exports hub', () => {
  it('lists every export with its layout, for anyone who may read or run exports', () => {
    const list = kit.exports.list(kit.actorFor(MANAGEMENT));
    expect(list).toHaveLength(14);
    expect(list.find((e) => e.code === 'sales_register')).toMatchObject({
      title: 'Sales register',
      schemaVersion: 1,
    });
    expect(list[0]?.columns.at(-1)).toEqual({ key: 'account_code', type: 'text' });
    expect(() => kit.exports.list(kit.actorFor(NOBODY))).toThrow('Not allowed');
    expect(() => kit.exports.list(kit.actorFor(SUPERVISOR))).toThrow('Not allowed');
  });
});

describe('running an export (BR-4 to BR-8)', () => {
  it('writes an Excel and a CSV file with the header block, rows, totals and footer', async () => {
    scriptReceipts();
    await inTx((tx) =>
      kit.tagging.tagTransaction(
        { docType: 'receipt', docId: 'doc-RV-1' },
        '1210',
        accountant(),
        tx,
      ),
    );
    const result = await run();
    expect(result.untagged).toBe(1);
    expect(result.totals).toEqual({ amount: '350500.50', withheld: '0.00' });
    expect(result.run).toMatchObject({
      exportCode: 'receipts_register',
      schemaVersion: 1,
      rowCount: 2,
      filters: period,
      runBy: ACCOUNTANT,
      fileId: result.files.xlsx,
    });
    expect(result.run.checksumSha256).toMatch(/^[0-9a-f]{64}$/);
    expect(kit.attached.map((a) => [a.entityType, a.entityId, a.fileName])).toEqual([
      ['acc_export_run', result.run.id, 'receipts_register-2026-10-01-2026-10-31.xlsx'],
      ['acc_export_run', result.run.id, 'receipts_register-2026-10-01-2026-10-31.csv'],
    ]);

    const csv = Buffer.from(kit.attached[1]?.bytes as Uint8Array).toString('utf8');
    expect(csv.charCodeAt(0)).toBe(0xfeff);
    expect(csv).toContain('Report,Receipts register');
    expect(csv).toContain('Untagged lines,1');
    expect(csv).toContain('Schema version,1');
    expect(csv).toContain('Fiscal year,FY2026-27');
    expect(csv).toContain('Period,2026-10-01 to 2026-10-31');
    expect(csv).toContain('Generated by,accountant@example.test');
    expect(csv).toContain('Generated at (Asia/Karachi),25/10/2026 15:00');
    expect(csv).toContain(
      'fiscal_year,month,date,number,party,method,amount,withheld,account_code',
    );
    expect(csv).toContain(
      'FY2026-27,2026-10,2026-10-05,RV-1,Synthetic Client,bank_transfer,100000.00,0.00,1210',
    );
    expect(csv).toContain(
      'FY2026-27,2026-10,2026-10-05,RV-2,Synthetic Client,bank_transfer,250500.50,0.00,\r\n',
    );
    expect(csv).toContain('row_count,2');
    expect(csv).toContain('Total,,,,,,350500.50,0.00,\r\n');

    const book = new ExcelJS.Workbook();
    await book.xlsx.load(Buffer.from(kit.attached[0]?.bytes as Uint8Array) as never);
    const sheet = book.worksheets[0];
    expect(sheet?.name).toBe('Receipts register');
    const amounts: number[] = [];
    sheet?.eachRow((row) => {
      const cell = row.getCell(7).value;
      if (typeof cell === 'number') amounts.push(cell);
    });
    expect(amounts).toEqual([100000, 250500.5, 350500.5]);
  });

  it('names the user id in the header when the caller has no display name', async () => {
    scriptReceipts();
    await run('receipts_register', period, { ...accountant(), name: undefined });
    const csv = Buffer.from(kit.attached.at(-1)?.bytes as Uint8Array).toString('utf8');
    expect(csv).toContain(`Generated by,${ACCOUNTANT}\r\n`);
  });

  it('logs the run, audits it and publishes an event', async () => {
    scriptReceipts();
    const result = await run();
    const logged = await kit.db.query<{ export_code: string; row_count: number }>(
      'select export_code, row_count from acc_export_runs where id = $1',
      [result.run.id],
    );
    expect(logged).toEqual([{ export_code: 'receipts_register', row_count: 2 }]);
    const audit = await kit.db.query<{ action: string }>(
      'select action from sys_audit_log where entity_id = $1',
      [result.run.id],
    );
    expect(audit.map((a) => a.action)).toEqual(['accounting.export.run']);
    const events = await kit.db.query<{ n: number }>(
      `select count(*) as n from sys_outbox where type = 'accounting.export.run'
        and payload->>'runId' = $1`,
      [result.run.id],
    );
    expect(Number(events[0]?.n)).toBe(1);
    const history = await kit.exports.runs(
      kit.db,
      { exportCode: 'receipts_register', limit: 1, offset: 0 },
      accountant(),
    );
    expect(history.items[0]?.id).toBe(result.run.id);
    expect(history.total).toBeGreaterThanOrEqual(1);
    const everything = await kit.exports.runs(
      kit.db,
      { limit: 50, offset: 0 },
      kit.actorFor(MANAGEMENT),
    );
    expect(everything.items.length).toBeGreaterThanOrEqual(1);
    await expect(
      kit.exports.runs(kit.db, { limit: 5, offset: 0 }, kit.actorFor(NOBODY)),
    ).rejects.toMatchObject({ code: 'forbidden' });
  });

  it('gives the same checksum for unchanged data on another day, and another for changed data (T-5)', async () => {
    scriptReceipts();
    const first = await run();
    kit.now.current = new Date('2026-11-02T04:00:00Z');
    const second = await run('receipts_register', period, kit.actorFor(MANAGEMENT));
    expect(second.run.id).not.toBe(first.run.id);
    expect(second.run.checksumSha256).toBe(first.run.checksumSha256);
    kit.loaded.receipts_register = {
      rows: [receiptRow('RV-1', '100000.00'), receiptRow('RV-2', '250500.51')],
      control: { amount: '350500.51', withheld: '0.00' },
    };
    const third = await run();
    expect(third.run.checksumSha256).not.toBe(first.run.checksumSha256);
    // A new tag changes the account_code column and so the data section.
    scriptReceipts();
    await inTx((tx) =>
      kit.tagging.tagTransaction(
        { docType: 'receipt', docId: 'doc-RV-2' },
        '1210',
        accountant(),
        tx,
      ),
    );
    expect((await run()).run.checksumSha256).not.toBe(first.run.checksumSha256);
  });

  it('labels the fiscal year by the setting: a July start and a January start (T-6, BR-7)', async () => {
    scriptReceipts();
    const july = await run();
    expect(july.run.id).toBeDefined();
    const csvOf = () => Buffer.from(kit.attached.at(-1)?.bytes as Uint8Array).toString('utf8');
    expect(csvOf()).toContain('Fiscal year,FY2026-27\r\n');
    await setFiscalStart(1, 0);
    await run();
    expect(csvOf()).toContain('Fiscal year,FY2026\r\n');
    await setFiscalStart(7, 1);
  });

  it('aborts and writes nothing when the rows do not tie out to the owning module (T-2)', async () => {
    kit.loaded.receipts_register = {
      rows: [receiptRow('RV-1', '100000.00')],
      control: { amount: '99999.00', withheld: '0.00' },
    };
    const before = (await kit.db.query('select 1 from acc_export_runs')).length;
    await expect(run()).rejects.toMatchObject({
      code: 'control_total_mismatch',
      kind: 'rule_violation',
      details: { mismatches: [{ column: 'amount', exported: '100000.00', owning: '99999.00' }] },
    });
    expect(kit.attached).toHaveLength(0);
    expect(await kit.db.query('select 1 from acc_export_runs')).toHaveLength(before);
  });

  it('keeps rows that are not document lines blank in account_code and untagged out of the warning count', async () => {
    kit.loaded.pdc_register = {
      rows: [
        {
          values: {
            cheque_no: '000123',
            bank: 'Synthetic Bank',
            party: 'Synthetic Client',
            cheque_date: '2026-10-20',
            status: 'received',
            cleared_on: null,
            amount: '5000.00',
          },
        },
      ],
      control: { amount: '5000.00' },
    };
    const result = await run('pdc_register');
    expect(result.untagged).toBe(0);
    expect(result.totals).toEqual({ amount: '5000.00' });
  });

  it('refuses a caller without the run permission, a backwards period and an unknown export', async () => {
    await expect(run('receipts_register', period, kit.actorFor(NOBODY))).rejects.toMatchObject({
      code: 'forbidden',
    });
    await expect(
      run('receipts_register', { from: '2026-10-31', to: '2026-10-01' }),
    ).rejects.toMatchObject({ code: 'invalid_period' });
    await expect(run('trial_balance' as ExportCode)).rejects.toMatchObject({
      code: 'unknown_export',
    });
  });
});
