import { layoutOf } from '@emporium/domain/accounting';
import ExcelJS from 'exceljs';
import { describe, expect, it } from 'vitest';
import { headerLines, karachiStamp, renderCsv, renderXlsx, type Rendered } from './render.js';

const layout = layoutOf('stock_valuation');
const rendered = (over: Partial<Rendered> = {}): Rendered => ({
  layout,
  rows: [
    {
      values: {
        store: '=cmd|calc',
        category: 'Cement, "grey"',
        method: 'fifo',
        quantity: '12.5000',
        value: '1500.25',
        account_code: null,
      },
    },
    {
      values: {
        store: 'Main',
        category: null,
        method: 'weighted_average',
        quantity: '1.0000',
        value: '10.00',
      },
    },
  ],
  totals: { value: '1510.25' },
  header: {
    name: 'Stock valuation',
    filters: {},
    period: '2026-10-01 to 2026-10-31',
    fiscalYear: 'FY2026-27',
    schemaVersion: 1,
    generatedAt: new Date('2026-10-25T19:30:00Z'),
    generatedBy: 'Synthetic Accountant',
    warnings: 0,
  },
  ...over,
});

describe('export files (BR-4, BR-6)', () => {
  it('stamps the time in Asia/Karachi, across midnight', () => {
    expect(karachiStamp(new Date('2026-10-25T10:00:00Z'))).toBe('25/10/2026 15:00');
    expect(karachiStamp(new Date('2026-10-25T19:30:00Z'))).toBe('26/10/2026 00:30');
  });

  it('writes the header block with the filters or "none"', () => {
    expect(headerLines(rendered().header)[1]).toEqual(['Filters', 'none']);
    const filtered = headerLines({ ...rendered().header, filters: { from: 'a', to: 'b' } });
    expect(filtered[1]).toEqual(['Filters', 'from: a; to: b']);
    expect(filtered.map(([label]) => label)).toEqual([
      'Report',
      'Filters',
      'Period',
      'Fiscal year',
      'Schema version',
      'Generated at (Asia/Karachi)',
      'Generated by',
      'Untagged lines',
    ]);
  });

  it('writes a CSV with a byte order mark, quoted fields, blanks and no live formulas', () => {
    const csv = renderCsv(rendered());
    expect(csv.startsWith('﻿Report,Stock valuation\r\n')).toBe(true);
    expect(csv).toContain('\'=cmd|calc,"Cement, ""grey""",fifo,12.5000,1500.25,\r\n');
    expect(csv).toContain('Main,,weighted_average,1.0000,10.00,\r\n');
    expect(csv).toContain('row_count,2\r\nTotal,,,,1510.25,\r\n');
  });

  it('leaves a money column of the totals row blank when no total is given for it', () => {
    const csv = renderCsv(rendered({ totals: {} }));
    expect(csv).toContain('row_count,2\r\nTotal,,,,,\r\n');
  });

  it('writes an Excel workbook with numbers as numbers and a bold totals row', async () => {
    const book = new ExcelJS.Workbook();
    await book.xlsx.load((await renderXlsx(rendered())) as never);
    const sheet = book.worksheets[0];
    expect(sheet?.name).toBe('Stock valuation');
    const rows: unknown[][] = [];
    sheet?.eachRow((row) => rows.push((row.values as unknown[]).slice(1)));
    expect(rows[8]).toEqual(['store', 'category', 'method', 'quantity', 'value', 'account_code']);
    expect(rows[9]?.slice(0, 5)).toEqual(['=cmd|calc', 'Cement, "grey"', 'fifo', 12.5, 1500.25]);
    expect(rows.at(-1)?.slice(0, 5)).toEqual(['Total', undefined, undefined, undefined, 1510.25]);
    expect(sheet?.lastRow?.getCell(1).font?.bold).toBe(true);
  });
});
