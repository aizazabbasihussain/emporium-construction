import type { ExportLayout, ExportRow } from '@emporium/domain/accounting';
import ExcelJS from 'exceljs';

/** BR-4: what the header block of an export carries. */
export interface Header {
  name: string;
  filters: Record<string, string>;
  period: string;
  fiscalYear: string;
  schemaVersion: number;
  generatedAt: Date;
  generatedBy: string;
  /** BR-2: the number of document lines in the export without an account code. */
  warnings: number;
}

export interface Rendered {
  layout: ExportLayout;
  rows: readonly ExportRow[];
  /** BR-4: the sum of each money column. */
  totals: Readonly<Record<string, string>>;
  header: Header;
}

const KARACHI_OFFSET_MS = 5 * 60 * 60 * 1000;

/** BR-4: generated at, in Asia/Karachi, as dd/mm/yyyy hh:mm. */
export function karachiStamp(at: Date): string {
  const local = new Date(at.getTime() + KARACHI_OFFSET_MS).toISOString();
  const [date, time] = local.split('T') as [string, string];
  const [year, month, day] = date.split('-') as [string, string, string];
  return `${day}/${month}/${year} ${time.slice(0, 5)}`;
}

/** The header block as label and value pairs, above the data. */
export function headerLines(header: Header): [string, string][] {
  const filters = Object.entries(header.filters).map(([key, value]) => `${key}: ${value}`);
  return [
    ['Report', header.name],
    ['Filters', filters.length === 0 ? 'none' : filters.join('; ')],
    ['Period', header.period],
    ['Fiscal year', header.fiscalYear],
    ['Schema version', String(header.schemaVersion)],
    ['Generated at (Asia/Karachi)', karachiStamp(header.generatedAt)],
    ['Generated by', header.generatedBy],
    ['Untagged lines', String(header.warnings)],
  ];
}

/** A text a spreadsheet would run as a formula is written with a leading quote. */
const safeText = (value: string): string => (/^[=+\-@\t\r]/.test(value) ? `'${value}` : value);

const csvField = (text: string): string =>
  /[",\r\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;

/** Excel opens a UTF-8 CSV with the right characters only when it starts with this mark. */
const BYTE_ORDER_MARK = String.fromCharCode(0xfeff);

/**
 * BR-4, BR-6: CSV with the header block, the data section under the column keys of the layout, a
 * footer with the row count and the control totals, UTF-8 with a byte order mark.
 */
export function renderCsv({ layout, rows, totals, header }: Rendered): string {
  const lines: string[] = headerLines(header).map(
    ([label, value]) => `${csvField(label)},${csvField(value)}`,
  );
  lines.push('', layout.columns.map((column) => column.key).join(','));
  for (const row of rows) {
    lines.push(
      layout.columns
        .map((column) => {
          const value = row.values[column.key];
          if (value === null || value === undefined) return '';
          return csvField(column.type === 'text' ? safeText(String(value)) : String(value));
        })
        .join(','),
    );
  }
  lines.push(
    '',
    `row_count,${rows.length}`,
    layout.columns
      .map((column, index) =>
        column.type === 'money' ? (totals[column.key] ?? '') : index === 0 ? 'Total' : '',
      )
      .join(','),
  );
  return `${BYTE_ORDER_MARK}${lines.join('\r\n')}\r\n`;
}

const NUMBER_FORMATS: Record<string, string> = { money: '#,##0.00', qty: '#,##0.0000', int: '0' };

/** BR-6: an Excel workbook with the same content, numbers stored as numbers. */
export async function renderXlsx({ layout, rows, totals, header }: Rendered): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.created = header.generatedAt;
  const sheet = workbook.addWorksheet(layout.title.slice(0, 31));
  for (const [label, value] of headerLines(header)) {
    sheet.addRow([label, value]).getCell(1).font = { bold: true };
  }
  sheet.addRow([]);
  sheet.addRow(layout.columns.map((column) => column.key)).font = { bold: true };
  const cell = (type: string, value: string | number | null | undefined) => {
    if (value === null || value === undefined) return null;
    return type === 'text' || type === 'date' ? String(value) : Number(value);
  };
  const format = (added: ExcelJS.Row) =>
    layout.columns.forEach((column, index) => {
      const pattern = NUMBER_FORMATS[column.type];
      if (pattern !== undefined) added.getCell(index + 1).numFmt = pattern;
    });
  for (const row of rows) {
    format(sheet.addRow(layout.columns.map((column) => cell(column.type, row.values[column.key]))));
  }
  sheet.addRow([]);
  sheet.addRow(['row_count', rows.length]);
  const total = sheet.addRow(
    layout.columns.map((column, index) =>
      column.type === 'money' ? cell('money', totals[column.key]) : index === 0 ? 'Total' : null,
    ),
  );
  total.font = { bold: true };
  format(total);
  layout.columns.forEach((column, index) => {
    sheet.getColumn(index + 1).width = Math.max(12, Math.min(column.key.length + 4, 40));
  });
  return Buffer.from(await workbook.xlsx.writeBuffer());
}
