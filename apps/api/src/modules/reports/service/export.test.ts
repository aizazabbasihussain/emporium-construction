import ExcelJS from 'exceljs';
import { describe, expect, it } from 'vitest';
import { headerBlock, karachiTime, toCsv, toXlsx, type ExportMeta } from './export.js';
import type { Section } from '../types.js';

const meta: ExportMeta = {
  code: 'stock',
  filters: { ownership: 'company', mystery: 'x', empty: '' },
  generatedAt: new Date('2026-10-25T20:30:00Z'),
  generatedBy: 'Zainab "the owner" Khan, Lahore',
};

const section: Section = {
  key: 'unknown_section',
  columns: [
    { key: 'itemName', type: 'text' },
    { key: 'unknownColumn', type: 'text' },
    { key: 'quantity', type: 'qty' },
    { key: 'value', type: 'money' },
    { key: 'when', type: 'date' },
  ],
  rows: [
    {
      itemName: '=SUM(A1:A9)',
      unknownColumn: 'Cement, grade "43"',
      quantity: '12.5000',
      value: '-10.00',
      when: '2026-10-20',
    },
    { itemName: '+1', unknownColumn: '-x\nline', quantity: null, value: '1234.50' },
    { itemName: '@cmd', unknownColumn: '\tTab', quantity: '0.0000', value: '0.00', when: null },
  ],
  totals: { value: '1224.50' },
};

describe('header block (BR-10)', () => {
  it('names the report, the filters, the Karachi time and the user', () => {
    expect(headerBlock(meta)).toEqual([
      ['Report', 'Stock on hand'],
      ['Filters', 'Ownership: company; mystery: x'],
      ['Generated at (Asia/Karachi)', '26/10/2026 01:30'],
      ['Generated by', 'Zainab "the owner" Khan, Lahore'],
    ]);
    expect(headerBlock({ ...meta, filters: {} })[1]).toEqual(['Filters', 'None']);
    expect(karachiTime(new Date('2026-12-31T19:30:00Z'))).toBe('01/01/2027 00:30');
  });
});

describe('CSV', () => {
  const csv = toCsv({ main: section, extras: [] }, meta);
  const lines = csv.split('\r\n');

  it('starts with a byte order mark, the header block and the table', () => {
    expect(csv.startsWith('﻿')).toBe(true);
    expect(lines[0]).toBe('﻿Report,Stock on hand');
    // A value with a comma and quotes is quoted and its quotes doubled.
    expect(lines[3]).toBe('Generated by,"Zainab ""the owner"" Khan, Lahore"');
    expect(lines[5]).toBe('unknown_section');
    expect(lines[6]).toBe('Item name,unknownColumn,Quantity,Value,when');
  });

  it('quotes cells that need it and defuses text a spreadsheet would run as a formula', () => {
    expect(lines[7]).toBe(`'=SUM(A1:A9),"Cement, grade ""43""",12.5000,-10.00,2026-10-20`);
    // The cell with a line break stays in one quoted field.
    expect(csv).toContain(`"'-x\nline"`);
    expect(lines[8]).toBe(`'+1,"'-x\nline",,1234.50,`);
    expect(csv).toContain(`'@cmd,'\tTab,0.0000,0.00,`);
  });

  it('ends the table with a totals row labelled in its first column, and a final line break', () => {
    expect(lines.at(-2)).toBe('Total,,,1224.50,');
    expect(csv.endsWith('\r\n')).toBe(true);
    const noTotals = toCsv({ main: { ...section, totals: null }, extras: [] }, meta);
    expect(noTotals).not.toContain('Total,');
  });

  it('writes each further table after a blank line', () => {
    const more = toCsv(
      { main: section, extras: [{ ...section, key: 'below_reorder', totals: null }] },
      meta,
    );
    expect(more).toContain('\r\n\r\nBelow reorder level\r\n');
  });
});

describe('Excel', () => {
  it('writes numbers as numbers with formats, text as text and empty cells empty', async () => {
    const buffer = await toXlsx(
      {
        main: section,
        extras: [{ key: 'below_reorder', columns: section.columns, rows: [], totals: null }],
      },
      meta,
    );
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(buffer as unknown as ArrayBuffer);
    const sheet = workbook.worksheets[0] as ExcelJS.Worksheet;
    expect(sheet.name).toBe('Stock on hand');
    expect(sheet.getRow(4).getCell(2).value).toBe('Zainab "the owner" Khan, Lahore');
    const first = sheet.getRow(8);
    // Text is never turned into a formula by the writer.
    expect(first.getCell(1).value).toBe('=SUM(A1:A9)');
    expect(first.getCell(3).value).toBe(12.5);
    expect(first.getCell(3).numFmt).toBe('#,##0.0000');
    expect(first.getCell(4).value).toBe(-10);
    expect(first.getCell(5).value).toBe('2026-10-20');
    expect(sheet.getRow(9).getCell(3).value).toBeNull();
    expect(sheet.getRow(9).getCell(5).value).toBeNull();
    const total = sheet.getRow(11);
    expect(total.getCell(1).value).toBe('Total');
    expect(total.getCell(4).value).toBe(1224.5);
    expect(total.font?.bold).toBe(true);
    expect(sheet.getRow(13).getCell(1).value).toBe('Below reorder level');
  });

  it('works without totals and gives a long column a width of at most 50', async () => {
    const wide: Section = {
      key: 'stock',
      columns: [{ key: 'itemName', type: 'text' }],
      rows: [{ itemName: 'x'.repeat(200) }],
      totals: null,
    };
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(
      (await toXlsx({ main: wide, extras: [] }, meta)) as unknown as ArrayBuffer,
    );
    const sheet = workbook.worksheets[0] as ExcelJS.Worksheet;
    expect(sheet.getColumn(1).width).toBe(50);
    expect(sheet.rowCount).toBe(8);
  });
});
