import { en, formatDateTimeUtc, type ReportCode } from '@emporium/shared';
import ExcelJS from 'exceljs';
import type { Cell, Column, Row, Section } from '../types.js';

/** What an export carries besides the tables (BR-10). */
export interface ExportMeta {
  code: ReportCode;
  filters: Record<string, string>;
  generatedAt: Date;
  generatedBy: string;
}

export interface ExportInput {
  main: Section;
  extras: Section[];
}

const KARACHI_OFFSET_MS = 5 * 60 * 60 * 1000;

const labels = en.reports;
const columnLabel = (key: string): string => (labels.columns as Record<string, string>)[key] ?? key;
const sectionLabel = (key: string): string =>
  (labels.sections as Record<string, string>)[key] ?? key;
const filterLabel = (key: string): string => (labels.filters as Record<string, string>)[key] ?? key;

/** BR-10: generated at, in Asia/Karachi, as dd/mm/yyyy hh:mm. */
export const karachiTime = (at: Date): string =>
  formatDateTimeUtc(new Date(at.getTime() + KARACHI_OFFSET_MS));

/** BR-10: the header block above the tables: report name, filters, generated at, generated by. */
export function headerBlock(meta: ExportMeta): [string, string][] {
  const filters = Object.entries(meta.filters).filter(([, value]) => value !== '');
  return [
    [labels.header.report, labels.names[meta.code]],
    [
      labels.header.filters,
      filters.length === 0
        ? labels.header.none
        : filters.map(([key, value]) => `${filterLabel(key)}: ${value}`).join('; '),
    ],
    [labels.header.generatedAt, karachiTime(meta.generatedAt)],
    [labels.header.generatedBy, meta.generatedBy],
  ];
}

/** The tables of a report in the order they are written: the main list, then the others. */
const sectionsOf = (input: ExportInput): Section[] => [input.main, ...input.extras];

/** A totals row carries the label in its first column unless that column has a total. */
function totalsOf(section: Section): Row | null {
  if (section.totals === null) return null;
  const first = section.columns[0] as Column;
  return { [first.key]: labels.total, ...section.totals };
}

/** A text that a spreadsheet would run as a formula is written with a leading quote. */
const safeText = (value: string): string => (/^[=+\-@\t\r]/.test(value) ? `'${value}` : value);

function csvCell(column: Column, value: Cell | undefined): string {
  if (value === null || value === undefined) return '';
  const text = column.type === 'text' ? safeText(String(value)) : String(value);
  return /[",\r\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

const csvLine = (cells: readonly string[]): string => cells.join(',');

/** Excel opens a UTF-8 CSV with the right characters only when it starts with this mark. */
const BYTE_ORDER_MARK = String.fromCharCode(0xfeff);

/** BR-10: CSV with the header block, one table after another, UTF-8 with a byte order mark. */
export function toCsv(input: ExportInput, meta: ExportMeta): string {
  const quote = (text: string) => csvCell({ key: '', type: 'text' }, text);
  const lines = headerBlock(meta).map(([name, value]) => csvLine([quote(name), quote(value)]));
  for (const section of sectionsOf(input)) {
    lines.push('', quote(sectionLabel(section.key)));
    lines.push(csvLine(section.columns.map((column) => quote(columnLabel(column.key)))));
    const totals = totalsOf(section);
    for (const row of totals === null ? section.rows : [...section.rows, totals]) {
      lines.push(csvLine(section.columns.map((column) => csvCell(column, row[column.key]))));
    }
  }
  return `${BYTE_ORDER_MARK}${lines.join('\r\n')}\r\n`;
}

const NUMBER_FORMATS: Partial<Record<Column['type'], string>> = {
  money: '#,##0.00',
  qty: '#,##0.0000',
  percent: '0.00',
  int: '0',
};

function xlsxValue(column: Column, value: Cell | undefined): string | number | null {
  if (value === null || value === undefined) return null;
  return column.type === 'text' || column.type === 'date' ? String(value) : Number(value);
}

/** BR-10: an Excel workbook with the header block and the tables on one sheet, numbers as numbers. */
export async function toXlsx(input: ExportInput, meta: ExportMeta): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.created = meta.generatedAt;
  const sheet = workbook.addWorksheet(labels.names[meta.code].slice(0, 31));
  for (const [name, value] of headerBlock(meta)) {
    sheet.addRow([name, value]).getCell(1).font = { bold: true };
  }
  const widths: number[] = [];
  const widen = (index: number, text: string) => {
    widths[index] = Math.max(widths[index] ?? 10, Math.min(text.length + 2, 50));
  };
  for (const section of sectionsOf(input)) {
    sheet.addRow([]);
    sheet.addRow([sectionLabel(section.key)]).getCell(1).font = { bold: true, size: 12 };
    const head = sheet.addRow(section.columns.map((column) => columnLabel(column.key)));
    head.font = { bold: true };
    section.columns.forEach((column, index) => widen(index, columnLabel(column.key)));
    const totals = totalsOf(section);
    for (const row of totals === null ? section.rows : [...section.rows, totals]) {
      const added = sheet.addRow(
        section.columns.map((column) => xlsxValue(column, row[column.key])),
      );
      section.columns.forEach((column, index) => {
        const format = NUMBER_FORMATS[column.type];
        if (format !== undefined) added.getCell(index + 1).numFmt = format;
        widen(index, String(row[column.key] ?? ''));
      });
      if (row === totals) added.font = { bold: true };
    }
  }
  widths.forEach((width, index) => {
    sheet.getColumn(index + 1).width = width;
  });
  return Buffer.from(await workbook.xlsx.writeBuffer());
}
