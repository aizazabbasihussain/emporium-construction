#!/usr/bin/env node
// Validates the spec set and (with --write) regenerates specs/STATUS.md.
// Usage: node specs/tools/spec-index.mjs [--write]
// Checks: frontmatter, status values, id/filename/phase agreement, dependency existence,
// dependency cycles, required headings, human-input references.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STATUSES = ['not-started', 'in-progress', 'in-review', 'done', 'blocked'];
const HEADINGS = [
  'Purpose', 'Boundary', 'Data model', 'Business rules', 'API and UI',
  'Permissions', 'Test requirements', 'Acceptance criteria', 'Open inputs',
];
const errors = [];
const err = (file, msg) => errors.push(`${file}: ${msg}`);

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-z_]+):\s*(.*?)\s*(#.*)?$/);
    if (!kv) continue;
    const [, key, raw] = kv;
    if (raw.startsWith('[')) {
      out[key] = raw.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean);
    } else {
      out[key] = raw;
    }
  }
  return out;
}

// Human inputs
const inputsText = fs.readFileSync(path.join(root, '03-human-inputs.md'), 'utf8');
const inputIds = new Set([...inputsText.matchAll(/^\| (H-\d+) \|/gm)].map((m) => m[1]));
const inputStatus = Object.fromEntries(
  [...inputsText.matchAll(/^\| (H-\d+) \|.*\| (open|answered) \|$/gm)].map((m) => [m[1], m[2]]),
);

// Specs
const specs = new Map();
for (const dir of fs.readdirSync(root).filter((d) => /^phase-\d+$/.test(d)).sort()) {
  for (const file of fs.readdirSync(path.join(root, dir)).sort()) {
    if (!/^P\d+-\d+-.+\.md$/.test(file)) continue;
    const rel = `${dir}/${file}`;
    const text = fs.readFileSync(path.join(root, rel), 'utf8');
    const fm = parseFrontmatter(text);
    if (!fm) { err(rel, 'missing frontmatter'); continue; }
    for (const k of ['id', 'title', 'phase', 'module', 'status', 'depends_on', 'requires_inputs']) {
      if (fm[k] === undefined) err(rel, `frontmatter missing "${k}"`);
    }
    if (fm.id && !file.startsWith(fm.id + '-')) err(rel, `id ${fm.id} does not match filename`);
    if (fm.id && `phase-${fm.phase}` !== dir) err(rel, `phase ${fm.phase} does not match folder ${dir}`);
    if (fm.id && !fm.id.startsWith(`P${fm.phase}-`)) err(rel, `id ${fm.id} does not match phase ${fm.phase}`);
    if (fm.status && !STATUSES.includes(fm.status)) err(rel, `bad status "${fm.status}"`);
    if (specs.has(fm.id)) err(rel, `duplicate id ${fm.id}`);
    for (const h of fm.requires_inputs ?? []) {
      if (!inputIds.has(h)) err(rel, `unknown human input ${h}`);
    }
    let last = -1;
    HEADINGS.forEach((name, i) => {
      const re = new RegExp(`^## ${i + 1}\\. ${name}\\s*$`, 'm');
      const idx = text.search(re);
      if (idx < 0) err(rel, `missing heading "## ${i + 1}. ${name}"`);
      else if (idx < last) err(rel, `heading "${name}" out of order`);
      else last = idx;
    });
    if (!/^# P\d+-\d+ /m.test(text)) err(rel, 'missing H1 title line "# <ID> <Title>"');
    specs.set(fm.id, { ...fm, rel });
  }
}

// Dependencies
for (const s of specs.values()) {
  for (const d of s.depends_on ?? []) {
    if (!specs.has(d)) err(s.rel, `depends_on unknown spec ${d}`);
    if (d === s.id) err(s.rel, 'depends on itself');
  }
}
// Cycles
const state = new Map();
function visit(id, trail) {
  if (state.get(id) === 'done') return;
  if (state.get(id) === 'visiting') { errors.push(`dependency cycle: ${[...trail, id].join(' -> ')}`); return; }
  state.set(id, 'visiting');
  for (const d of specs.get(id)?.depends_on ?? []) if (specs.has(d)) visit(d, [...trail, id]);
  state.set(id, 'done');
}
for (const id of specs.keys()) visit(id, []);

// Report
if (errors.length) {
  console.error(`Spec check FAILED (${errors.length}):`);
  for (const e of errors) console.error(' - ' + e);
  process.exit(1);
}

const list = [...specs.values()].sort((a, b) =>
  a.id.localeCompare(b.id, undefined, { numeric: true }));
const isDone = (id) => specs.get(id)?.status === 'done';
const rows = list.map((s) => {
  const blockedBy = (s.depends_on ?? []).filter((d) => !isDone(d));
  const openInputs = (s.requires_inputs ?? []).filter((h) => inputStatus[h] !== 'answered');
  const ready = s.status === 'not-started' && blockedBy.length === 0;
  return `| ${s.id} | ${s.title} | ${s.status} | ${(s.depends_on ?? []).join(', ') || '-'} | ${ready ? 'yes' : 'no'} | ${openInputs.join(', ') || '-'} |`;
});
const counts = STATUSES.map((st) => `${st}: ${list.filter((s) => s.status === st).length}`).join(', ');
const out = [
  '# STATUS',
  '',
  '_Generated by `specs/tools/spec-index.mjs --write`. Do not edit by hand._',
  '',
  `Specs: ${list.length} (${counts})`,
  '',
  '"Ready" means status is not-started and every dependency is done. "Inputs not answered" lists human inputs still open (see 03-human-inputs.md).',
  '',
  '| ID | Title | Status | Depends on | Ready | Inputs not answered |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
].join('\n');

if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(root, 'STATUS.md'), out);
  console.log(`Spec check OK. STATUS.md written (${list.length} specs).`);
} else {
  console.log(`Spec check OK (${list.length} specs).`);
}
